<?php
/**
 * Writes public/css/syntax.css: the highlighter's colours for code blocks, a
 * light palette and a dark one, switched by the same theme rules site.css
 * uses. Run it again after changing either palette:
 *
 *   php bin/build-syntax-css.php
 *
 * The palettes are highlight.php's Solarized Light and Ocean, rewritten so
 * they apply only inside <pre class="hl-code"> and leave the frame (padding,
 * scrolling, layout), which site.css owns, alone.
 */

const LIGHT = 'solarized-light';
const DARK = 'ocean';

$root = dirname(__DIR__);
$styles = $root . '/packages/scrivo/highlight.php/styles/';

function scoped(string $css): string {
    $css = preg_replace('~/\*.*?\*/~s', '', $css);
    preg_match_all('~([^{}]+)\{([^}]*)\}~', $css, $rules, PREG_SET_ORDER);

    $out = '';
    foreach ($rules as [, $selectors, $body]) {
        $selectors = array_map('trim', explode(',', $selectors));
        $declarations = array_map('trim', array_filter(explode(';', $body), 'trim'));

        if ($selectors === ['.hljs']) {
            // The block itself: only its colours, the frame is site.css's.
            $declarations = array_filter($declarations, fn ($d) => preg_match('~^(color|background(-color)?)\s*:~', $d));
            $declarations = array_map(fn ($d) => preg_replace('~^background\s*:~', 'background-color:', $d), $declarations);
            $out .= ".hl-code {\n " . implode(";\n ", $declarations) . ";\n}\n";
            continue;
        }

        $prefixed = array_map(fn ($s) => '.hl-code ' . $s, $selectors);
        $out .= implode(', ', $prefixed) . " {\n " . implode(";\n ", $declarations) . ";\n}\n";
    }
    return $out;
}

$light = scoped(file_get_contents($styles . LIGHT . '.css'));
$dark = scoped(file_get_contents($styles . DARK . '.css'));

$css = "/* generated by bin/build-syntax-css.php - do not edit */\n"
    . "/* highlight.php \"" . LIGHT . "\" */\n" . $light
    . "/* highlight.php \"" . DARK . "\": the OS preference, unless an explicit light choice overrides it. */\n"
    . "@media (prefers-color-scheme: dark) {\n:root:not([data-theme=\"light\"]) {\n" . $dark . "}\n}\n"
    . "/* An explicit dark choice, whatever the OS says, but only on screen: site.css\n"
    . "   prints light, and this attribute selector would otherwise outrank print's\n"
    . "   :root and put a dark code background on a printed page. */\n"
    . "@media screen {\n:root[data-theme=\"dark\"] {\n" . $dark . "}\n}\n";

file_put_contents($root . '/public/css/syntax.css', $css);
echo "wrote public/css/syntax.css\n";
