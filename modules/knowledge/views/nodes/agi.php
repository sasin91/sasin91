<p>“Artificial general intelligence” is used in at least four quite different
senses:</p>
<ul>
<li><strong>Human-level breadth</strong>: performing at or above human level across most
cognitive tasks, not only one domain.</li>
<li><strong>Learning ability</strong>: acquiring new skills as efficiently as a person does,
from little data.</li>
<li><strong>Economic</strong>: doing most economically valuable work. OpenAI’s charter uses
a version of this, describing systems that “outperform humans at most
economically valuable work”.</li>
<li><strong>Graded</strong>: frameworks that drop the single threshold and rate systems by
levels of performance and generality instead.</li>
</ul>
<p>The disagreement is not just pedantry. “General” and “intelligence” are both
contested words, the definitions point to different measurements
(benchmark scores, job tasks, autonomy, learning speed), and organisations
have commercial and contractual reasons to prefer one or another.</p>
<p>So the useful question about any AGI claim is not yes or no, but: which
definition, measured how? A system can satisfy one definition comfortably
while clearly failing another.</p>
